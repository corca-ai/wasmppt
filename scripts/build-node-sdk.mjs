import { build } from 'esbuild'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const output = resolve(root, 'packages/wasmppt/generated/node.mjs')
const result = await build({
  absWorkingDir: root,
  entryPoints: ['packages/wasmppt/src/node.ts'],
  outfile: output,
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node24',
  external: ['../../wasmppt-worker/src/generated/wasmppt_wasm.js'],
  banner: { js: '// Generated by scripts/build-node-sdk.mjs. Edit the TypeScript SDK sources.' },
  write: false,
})
const bytes = result.outputFiles[0].contents
if (process.argv.includes('--check')) {
  const actual = await readFile(output)
  if (!actual.equals(Buffer.from(bytes))) throw new Error('Node SDK is stale; run npm run build:node')
} else {
  await mkdir(resolve(output, '..'), { recursive: true })
  await writeFile(output, bytes)
}
